import { expect, test } from '@playwright/test'

test('dashboard email review drives 10 to 410 to 395 and grounded paycheck answer',async({page})=>{
  await page.goto('/#circles')
  await page.getByLabel('Starting synthetic checking balance ($)',{exact:true}).fill('10')
  page.once('dialog',d=>d.accept())
  await page.getByRole('button',{name:'Start isolated walkthrough',exact:true}).click()
  await expect(page.getByText('ISOLATED SYNTHETIC SCENARIO',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Overview',exact:true}).click()
  await expect(page.getByTestId('balance')).toHaveText('$10.00')
  for(const [event,balance] of [['paycheck','$410.00'],['purchase','$395.00']]) {
    await page.getByRole('button',{name:event==='paycheck'?'Simulate $400 paycheck email':'Simulate $15 purchase email',exact:true}).click()
    const item=page.locator('.gmail-review')
    await expect(item).toContainText('Simulated')
    await expect(item.getByRole('button',{name:'Confirm email transaction',exact:true})).toBeDisabled()
    await item.getByRole('checkbox').check()
    await item.getByRole('button',{name:'Confirm email transaction',exact:true}).click()
    await expect(page.getByTestId('balance')).toHaveText(balance)
  }
  await page.screenshot({path:'../.runtime/final-dashboard-approvals.png',fullPage:true})
  await page.getByRole('button',{name:'AI Assistant',exact:true}).click()
  await page.getByRole('button',{name:'When was my last confirmed paycheck?',exact:true}).click()
  await expect(page.locator('.chat-message.assistant')).toContainText('$400.00')
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
})

test('savings contribution and planned completion do not create cash',async({page})=>{
  await page.goto('/#settings')
  page.once('dialog',d=>d.accept())
  await page.getByRole('button',{name:'Reset Demo',exact:true}).click()
  const before=await (await page.request.get('/api/dashboard')).json()
  await page.getByLabel('Planned monthly contribution ($)',{exact:true}).fill('100')
  await page.getByRole('button',{name:'Save contribution plan',exact:true}).click()
  await expect(page.getByText(/Estimated completion:/)).toBeVisible()
  await page.getByLabel('Recorded contribution ($)',{exact:true}).fill('25')
  await page.getByRole('button',{name:'Record goal contribution',exact:true}).click()
  await expect(page.getByText(/recorded contribution$/)).toBeVisible()
  const after=await (await page.request.get('/api/dashboard')).json()
  expect(after.balance).toBe(before.balance)
  await page.getByRole('button',{name:'AI Assistant',exact:true}).click()
  await page.getByRole('button',{name:'Am I on track with my savings goal?',exact:true}).click()
  await expect(page.locator('.chat-message.assistant')).toContainText('not deposited money')
})


test('account tools link debit cards, transfer once and reconcile observed cash',async({page})=>{
  await page.goto('/#circles')
  await page.getByLabel('Starting synthetic checking balance ($)',{exact:true}).fill('10')
  page.once('dialog',d=>d.accept())
  await page.getByRole('button',{name:'Start isolated walkthrough',exact:true}).click()
  await expect(page.getByText('ISOLATED SYNTHETIC SCENARIO',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Settings',exact:true}).click()
  await page.getByRole('button',{name:'Add synthetic account',exact:true}).click()
  await page.getByLabel('Debit card last four',{exact:true}).fill('4321')
  await page.getByRole('button',{name:'Link debit card',exact:true}).click()
  await expect(page.getByText(/Everyday debit/)).toBeVisible()
  await page.getByLabel('Transfer to',{exact:true}).selectOption({label:'Savings (savings)'})
  await page.getByLabel('Transfer amount ($)',{exact:true}).fill('1')
  await page.getByRole('button',{name:'Record internal transfer',exact:true}).click()
  await expect(page.locator('.toast')).toContainText('Internal transfer recorded once')
  await page.getByLabel('Observed balance ($)',{exact:true}).fill('8')
  await page.getByRole('checkbox',{name:'I checked this balance. Credit debt uses a negative balance.',exact:true}).check()
  await page.getByRole('button',{name:'Reconcile balance',exact:true}).click()
  await expect(page.locator('.toast')).toContainText('Balance reconciled')
  const data=await (await page.request.get('/api/dashboard')).json()
  expect([data.balance,data.income,data.expenses]).toEqual([9,0,0])
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
})
