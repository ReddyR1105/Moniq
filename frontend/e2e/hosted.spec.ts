import { test, expect } from '@playwright/test'

test('welcome and simulated Gmail approvals work on desktop and stay isolated @hosted',async({page,browser})=>{
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'Your money. A little more clarity.'})).toBeVisible()
  await expect(page.getByTestId('balance')).toHaveCount(0)
  await page.getByRole('button',{name:'Try Demo',exact:true}).first().click()
  await expect(page.getByTestId('balance')).toBeVisible()
  await expect(page.getByRole('heading',{name:'Try Gmail Transaction Demo'})).toBeVisible()
  page.once('dialog',dialog=>dialog.accept())
  await page.getByRole('button',{name:'Start simulated Gmail demo'}).click()
  await expect(page.getByTestId('balance')).toHaveText('$10.00')
  for(const [alert,balance] of [['Receive $400 paycheck alert','$410.00'],['Receive $15 purchase alert','$395.00']]){
    await page.getByRole('button',{name:alert}).click()
    const review=page.locator('.gmail-review').first()
    await review.getByRole('checkbox').check()
    await review.getByRole('button',{name:'Confirm email transaction'}).click()
    await expect(page.getByTestId('balance')).toHaveText(balance)
  }
  const second=await browser.newContext({ignoreHTTPSErrors:true})
  const visitor=await second.newPage()
  await visitor.goto('https://127.0.0.1:8005/')
  await expect(visitor.getByRole('heading',{name:'Your money. A little more clarity.'})).toBeVisible()
  expect((await visitor.request.get('https://127.0.0.1:8005/api/gmail/status')).status()).toBe(403)
  await second.close()
  await page.screenshot({path:'../.runtime/hosted-test-results/simulated-gmail-desktop.png',fullPage:true})
})

test('private login, Gmail controls, logout and mobile welcome @hosted',async({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto('/')
  await page.getByRole('button',{name:'Log In',exact:true}).first().click()
  await page.getByLabel('Email address').fill('student@moniq.example.test')
  await page.getByLabel('Password',{exact:true}).fill('synthetic student password 123')
  await page.locator('form').getByRole('button',{name:'Log In',exact:true}).click()
  await expect(page.getByText('PERSONAL WORKSPACE',{exact:true}).first()).toBeVisible()
  await expect(page.getByTestId('balance')).toHaveText('$0.00')
  await page.getByRole('button',{name:'Gmail & accounts'}).click()
  await expect(page.getByRole('heading',{name:'Gmail financial alerts'})).toBeVisible()
  await expect(page.getByRole('button',{name:'Connect Gmail',exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'Connect Gmail',exact:true})).toBeDisabled()
  await page.screenshot({path:'../.runtime/hosted-test-results/private-settings-mobile.png',fullPage:true})
  await page.getByRole('button',{name:'Log Out'}).click()
  await expect(page.getByRole('heading',{name:'Your money. A little more clarity.'})).toBeVisible()
  expect((await page.request.get('/api/dashboard')).status()).toBe(401)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy()
})

test('emailed invitation creates a verified account and opens its empty desktop workspace @hosted',async({page})=>{
  await page.goto('/#invite=synthetic-invitation-code-123')
  await expect(page.getByRole('heading',{name:'Create your private space.'})).toBeVisible()
  expect(page.url()).not.toContain('synthetic-invitation')
  await page.getByLabel('Email address').fill('invited@moniq.example.test')
  await page.getByLabel('Password',{exact:true}).fill('synthetic invited password 456')
  await page.locator('form').getByRole('button',{name:'Create Account',exact:true}).click()
  await expect(page.getByText('Your account is created and your email is verified. Log in to your private workspace.')).toBeVisible()
  await page.getByLabel('Password',{exact:true}).fill('synthetic invited password 456')
  await page.locator('form').getByRole('button',{name:'Log In',exact:true}).click()
  await expect(page.getByTestId('balance')).toHaveText('$0.00')
  await page.getByRole('button',{name:'Gmail & accounts'}).click()
  await expect(page.getByRole('heading',{name:'Registered personal accounts'})).toBeVisible()
  await expect(page.getByRole('button',{name:'Sync Now',exact:true})).toBeDisabled()
  await expect(page.getByRole('button',{name:'Disconnect Gmail',exact:true})).toBeDisabled()
  await page.screenshot({path:'../.runtime/hosted-test-results/private-settings-desktop.png',fullPage:true})
  await page.getByRole('button',{name:'Log Out'}).click()
  await expect(page.getByRole('heading',{name:'Your money. A little more clarity.'})).toBeVisible()
})
