import { expect, test, type Page } from '@playwright/test'

test.use({video:{mode:'on',size:{width:1440,height:1000}}})

async function scenario(page:Page) {
  await page.goto('/#circles')
  await page.getByLabel('Starting synthetic checking balance ($)',{exact:true}).fill('100.00')
  page.once('dialog',d=>d.accept())
  await page.getByRole('button',{name:'Start isolated walkthrough',exact:true}).click()
  await expect(page.getByText('ISOLATED SYNTHETIC SCENARIO',{exact:true})).toBeVisible()
}

async function createCircle(page:Page,people='Jordan') {
  await page.getByRole('button',{name:'New circle',exact:true}).click()
  await page.getByLabel('Participants, separated by commas').fill(people)
  await page.getByRole('button',{name:'Create circle',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
}

test('controlled alert, linked equal split and cash repayment preserve accounting',async({page})=>{
  await scenario(page)
  await page.getByRole('button',{name:'Overview',exact:true}).click()
  await expect(page.getByTestId('balance')).toHaveText('$100.00')
  await page.getByRole('button',{name:'Circles',exact:true}).click()
  await page.getByRole('button',{name:'Process controlled $40 alert',exact:true}).click()
  await expect(page.locator('.toast')).toContainText('Estimated cash is $60')
  await createCircle(page)
  await page.getByLabel('Expense to split').selectOption({label:'Chick-fil-A · $40.00 · #1'})
  await page.getByRole('button',{name:'Split with Friends',exact:true}).click()
  await expect(page.getByLabel('Expense amount (USD)')).toHaveValue('40')
  await page.getByRole('button',{name:'Save shared expense',exact:true}).click()
  await expect(page.getByTestId('circle-receivable')).toHaveText('$20.00')
  await expect(page.locator('.circle-expense')).toContainText('Me · share $20.00')
  await page.getByRole('button',{name:'Mark as paid / partial repayment',exact:true}).click()
  await page.getByLabel('Record an actual bank cash movement').check()
  await page.getByLabel('I confirmed this repayment happened.',{exact:true}).check()
  await page.getByRole('button',{name:'Save repayment',exact:true}).click()
  await expect(page.getByTestId('circle-receivable')).toHaveText('$0.00')
  await expect(page.getByText('All recorded shares are clear.',{exact:true})).toBeVisible()
  await page.evaluate(()=>{(document.activeElement as HTMLElement)?.blur();window.scrollTo(0,0)})
  await page.screenshot({path:'../.runtime/circles-upgrade.png',fullPage:true})
  await page.getByRole('button',{name:'Overview',exact:true}).click()
  await expect(page.getByTestId('balance')).toHaveText('$80.00')
  const data=await (await page.request.get('/api/dashboard')).json()
  expect([data.balance,data.expenses,data.income,data.cash_expenses]).toEqual([80,20,0,40])
  await expect(page.getByText('ESTIMATED BALANCE',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'AI Assistant',exact:true}).click()
  await page.getByRole('button',{name:'How much do my roommates owe me?',exact:true}).click()
  await expect(page.locator('.chat-message.assistant')).toContainText('$0.00 owed to you')
})

test('custom amounts, percentages, exclusions, edit and partial bookkeeping repayments',async({page})=>{
  await scenario(page)
  await createCircle(page,'Jordan')
  await page.getByLabel('Add a local participant',{exact:true}).fill('Sam')
  await page.getByRole('button',{name:'Add participant',exact:true}).click()
  await expect(page.locator('.circle-detail')).toContainText('Me · Jordan · Sam')
  await page.getByRole('button',{name:'Add shared expense',exact:true}).click()
  await page.getByLabel('Expense amount (USD)').fill('60')
  await page.getByLabel('Split method').selectOption('amount')
  await page.getByLabel('Share amount for Me',{exact:true}).fill('10')
  await page.getByLabel('Share amount for Jordan',{exact:true}).fill('20')
  await page.getByLabel('Share amount for Sam',{exact:true}).fill('30')
  await page.getByRole('button',{name:'Save shared expense',exact:true}).click()
  await expect(page.getByTestId('circle-receivable')).toHaveText('$50.00')
  await page.getByRole('button',{name:'Edit Shared dinner',exact:true}).click()
  await page.getByLabel('Split method').selectOption('percentage')
  await page.getByLabel('Sam',{exact:true}).uncheck()
  await page.getByLabel('Percent for Me',{exact:true}).fill('25')
  await page.getByLabel('Percent for Jordan',{exact:true}).fill('75')
  await page.getByRole('button',{name:'Save shared expense',exact:true}).click()
  await expect(page.getByTestId('circle-receivable')).toHaveText('$45.00')
  await page.getByRole('button',{name:'Mark as paid / partial repayment',exact:true}).click()
  await page.getByLabel('Repayment amount',{exact:true}).fill('5')
  await page.getByLabel('I confirmed this repayment happened.',{exact:true}).check()
  await page.getByRole('button',{name:'Save repayment',exact:true}).click()
  await expect(page.getByTestId('circle-receivable')).toHaveText('$40.00')
  const data=await (await page.request.get('/api/dashboard')).json()
  expect([data.balance,data.expenses,data.income]).toEqual([100,15,0])
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
})

test('trusted sender defaults off, configurable limits, suspension and removal retain audit',async({page})=>{
  await scenario(page)
  await page.getByRole('button',{name:'Settings',exact:true}).click()
  await expect(page.getByLabel('Enable automatic approval for this sender')).not.toBeChecked()
  await page.getByLabel('Exact sender or domain').fill('alerts@second-synthetic.edu')
  await page.getByLabel('Financial institution',{exact:true}).fill('Synthetic Credit Union')
  await page.getByLabel('Per-transaction limit ($)').fill('20')
  await page.getByLabel('Daily approval limit ($)').fill('50')
  await page.getByRole('button',{name:'Add trusted sender',exact:true}).click()
  const card=page.locator('.gmail-review').filter({hasText:'Synthetic Credit Union'})
  await expect(card).toContainText('Auto-approval off')
  await card.getByRole('button',{name:'Edit sender',exact:true}).click()
  await page.getByLabel('Enable automatic approval for this sender').check()
  await page.getByLabel('Suspend this sender').check()
  await page.getByRole('button',{name:'Save sender changes',exact:true}).click()
  await expect(card).toContainText('suspended')
  page.once('dialog',d=>d.accept())
  await card.getByRole('button',{name:'Remove sender',exact:true}).click()
  await expect(card).toHaveCount(0)
  await expect(page.getByText(/rule-removed/)).toBeVisible()
})
